// Renders the main screens to PNGs without a display (used to check layouts against the mockups):
//   gradle :desktop:renderScreens -PscreensOut=/some/dir
tasks.register<JavaExec>("renderScreens") {
    group = "verification"
    dependsOn("testClasses")
    classpath = sourceSets["test"].runtimeClasspath
    mainClass.set("com.flowstate.desktop.RenderScreensKt")
    args(providers.gradleProperty("screensOut").orElse(layout.buildDirectory.dir("screens").get().asFile.path).get())
    systemProperty("java.awt.headless", "true")
}
