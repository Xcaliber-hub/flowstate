// Flowstate for Windows: Compose Multiplatform for the JVM desktop.
// It configures on any OS (the Android CI on Ubuntu includes this module); only :desktop:packageMsi
// needs Windows, because jpackage builds installers for the OS it runs on.
plugins {
    alias(libs.plugins.kotlin.jvm)
    alias(libs.plugins.kotlin.compose)
    alias(libs.plugins.kotlin.serialization)
    alias(libs.plugins.compose.multiplatform)
}

// One version for both apps: read versionName from the Android build so a release tag v<versionName>
// carries the APK and the MSI of the same version.
val appVersion: String = Regex("""versionName\s*=\s*"([^"]+)"""")
    .find(rootProject.file("app/build.gradle.kts").readText())?.groupValues?.get(1) ?: "1.0.0"

java {
    sourceCompatibility = JavaVersion.VERSION_17
    targetCompatibility = JavaVersion.VERSION_17
}
kotlin {
    compilerOptions { jvmTarget.set(JvmTarget.JVM_17) }
}

// Android-free domain code is compiled straight from the Android app's sources, so the timer model,
// stats maths and IST week/day helpers stay identical on both platforms. These files must not import
// android.* (androidx.compose.runtime.Immutable is fine: Compose Multiplatform has it too).
val sharedDomainDir = layout.buildDirectory.dir("generated/sharedDomain")
val syncSharedDomain by tasks.registering(Sync::class) {
    from(rootProject.file("app/src/main/java")) {
        include(
            "com/flowstate/focus/domain/AppSettings.kt",
            "com/flowstate/focus/domain/Models.kt",
            "com/flowstate/focus/domain/StatsCalculator.kt",
            "com/flowstate/focus/domain/WaterPhysics.kt",
            "com/flowstate/focus/domain/groups/*.kt",
        )
    }
    into(sharedDomainDir)
}

// Firebase client values, push relay URL and version come from the Android resources, so there is a
// single place to change them.
val generatedConfigDir = layout.buildDirectory.dir("generated/desktopConfig")
val generateDesktopConfig by tasks.registering {
    val firebaseXml = rootProject.file("app/src/main/res/values/flowstate_firebase.xml")
    val pushXml = rootProject.file("app/src/main/res/values/flowstate_push.xml")
    val version = appVersion
    inputs.files(firebaseXml, pushXml)
    inputs.property("version", version)
    outputs.dir(generatedConfigDir)
    doLast {
        fun read(file: File, name: String): String =
            Regex("""<string name="$name"[^>]*>([^<]*)</string>""").find(file.readText())?.groupValues?.get(1)?.trim().orEmpty()
        fun lit(s: String) = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
        val out = generatedConfigDir.get().file("com/flowstate/desktop/FlowstateConfig.kt").asFile
        out.parentFile.mkdirs()
        out.writeText(
            """
            |// Generated by :desktop:generateDesktopConfig from app/src/main/res/values. Do not edit.
            |package com.flowstate.desktop
            |
            |object FlowstateConfig {
            |    const val VERSION = ${lit(version)}
            |    const val FIREBASE_API_KEY = ${lit(read(firebaseXml, "flowstate_firebase_api_key"))}
            |    const val FIREBASE_PROJECT_ID = ${lit(read(firebaseXml, "flowstate_firebase_project_id"))}
            |    const val PUSH_URL = ${lit(read(pushXml, "flowstate_push_url"))}
            |}
            |""".trimMargin()
        )
    }
}

kotlin.sourceSets.named("main") {
    kotlin.srcDir(syncSharedDomain)
    kotlin.srcDir(generateDesktopConfig)
}

